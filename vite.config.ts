import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'path';
import { defineConfig, type Plugin } from 'vite';

/**
 * P6.4: emits dist/sw.js after every build — a small offline shell worker.
 * The precache list is generated from the real build output (hashed asset
 * names), and the cache version changes per build so switching releases
 * invalidates the previous shell on activate.
 */
const listDistFiles = (dir: string, root: string): string[] => {
  const files: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...listDistFiles(full, root));
    else files.push(path.relative(root, full).split(path.sep).join('/'));
  }
  return files;
};

const makeServiceWorker = (): string => {
  const dist = path.resolve(__dirname, 'dist');
  // '/' and '/index.html' are two cache keys for the same document — the
  // offline navigation fallback checks both first. Set-dedupe the whole list
  // because Cache.addAll hard-fails on duplicate request URLs.
  const assets = listDistFiles(dist, dist).filter((file) => file !== 'index.html');
  const buildId = Date.now().toString(36);
  const precache = JSON.stringify([...new Set(['/', '/index.html', ...assets])]);
  return `/* Color Flood Master service worker — generated by the build, do not edit. */
const VERSION = "${buildId}";
const CACHE = "cf-shell-" + VERSION;
const PRECACHE = ${precache};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // CDN + WebSocket pass through
  // Fresh document when online; cached app shell when the server is
  // unreachable (dead network rejects — a shell holds when the network
  // answers with an error response instead, e.g. proxy/500).
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).then(
        (response) => {
          if (response.ok) return response;
          return caches.match("/index.html").then((hit) => hit || response);
        },
        () => caches.match("/index.html").then((hit) => hit || Response.error())
      )
    );
    return;
  }
  // Hashed build assets never change once published: cache-first is safe.
  event.respondWith(
    caches.match(request).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches
              .open(CACHE)
              .then((cache) => cache.put(request, copy))
              .catch(() => {});
          }
          return response;
        })
    )
  );
});
`;
};

const serviceWorkerPlugin = (): Plugin => ({
  name: 'color-flood-service-worker',
  apply: 'build',
  closeBundle() {
    writeFileSync(path.resolve(__dirname, 'dist', 'sw.js'), makeServiceWorker());
  },
});

export default defineConfig(() => {
  return {
    plugins: [react(), tailwindcss(), serviceWorkerPlugin()],
    resolve: {
      alias: {
        '@': path.resolve(__dirname, '.'),
      },
    },
    server: {
      // HMR is disabled in AI Studio via DISABLE_HMR env var.
      // Do not modify — file watching is disabled to prevent flickering during agent edits.
      hmr: process.env.DISABLE_HMR !== 'true',
    },
  };
});
